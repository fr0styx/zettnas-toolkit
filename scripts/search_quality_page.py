"""docs/SEARCH_QUALITY.md, generated from the eval baselines (COMP-05).

    python scripts/search_quality_page.py           # compare (exit 1 when the page is out of date)
    python scripts/search_quality_page.py --update  # rewrite it

Every number on the page comes from tests/rag_eval/baseline*.json: the per-commit baselines that
CI holds (built-in lexical vectors) and the nightly ones recorded from GitHub's runners. Update
a baseline and the page in the same commit; tests/test_comp05_search_quality.py checks they agree.
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVAL = os.path.join(ROOT, "tests", "rag_eval")
PAGE = os.path.join(ROOT, "docs", "SEARCH_QUALITY.md")
LANGS = [("en", "English"), ("de", "German"), ("fr", "French"), ("es", "Spanish"), ("zh", "Chinese")]
KINDS = {
    "same-language": "Same language",
    "cross": "Cross-language",
    "paraphrase": "Paraphrased",
    "long": "Long documents",
    "office": "Office files",
    "scanned": "Scanned",
    "multihop": "Two files needed",
}


def load(name: str) -> dict | None:
    path = os.path.join(EVAL, name)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


MODEL_NAMES = {"embeddinggemma": "EmbeddingGemma", "qwen3:4b": "Qwen3-4B"}


def _model(name: str) -> str:
    return MODEL_NAMES.get(name, name)


def _sentence(text: str) -> str:
    text = text.strip().rstrip(".")
    return text[:1].upper() + text[1:] + "." if text else ""


def _n(v) -> str:
    return "—" if v is None else f"{v:.2f}"


def _table(rows: list[tuple[str, dict]], all5: bool = False) -> list[str]:
    head = "| | Questions | Right file first | Right file in top 5 |" + (" All files needed in top 5 |" if all5 else "")
    sep = "|---|---|---|---|" + ("---|" if all5 else "")
    out = [head, sep]
    for label, m in rows:
        line = f"| {label} | {m['queries']} | {_n(m['recall@1'])} | {_n(m['recall@5'])} |"
        if all5:
            line += f" {_n(m['all@5'])} |"
        out.append(line)
    return out


def _by_lang(d: dict) -> list[tuple[str, dict]]:
    rows = [(name, d["by_language"][code]) for code, name in LANGS if code in d.get("by_language", {})]
    return rows + [("**All**", d["overall"])]


def _by_kind(d: dict) -> list[tuple[str, dict]]:
    kinds = d.get("by_kind") or {}
    return [(KINDS.get(k, k), kinds[k]) for k in KINDS if k in kinds]


def _split(d: dict) -> str:
    s = d.get("by_split") or {}
    if "heldout" not in s or "dev" not in s:
        return ""
    return (
        f"Held-out half (never used for tuning): right file in the top 5 for {_n(s['heldout']['recall@5'])}"
        f" of {s['heldout']['queries']} questions, against {_n(s['dev']['recall@5'])} for the other"
        f" {s['dev']['queries']}."
    )


def render() -> str:
    base, docs, ext = load("baseline.json"), load("baseline_documents.json"), load("baseline_extended.json")
    night, night_docs, night_ans = (
        load("baseline_nightly.json"),
        load("baseline_nightly_documents.json"),
        load("baseline_nightly_answers.json"),
    )
    out = [
        "# Search quality",
        "",
        "<!-- generated by scripts/search_quality_page.py from tests/rag_eval/baseline*.json; do not edit -->",
        "",
        "How well Ask Zetty finds the right file, measured on a public test set anyone can rerun:",
        "40 home-NAS files in five languages with 200 hand-written questions, plus long, Office and",
        "scanned documents, cross-language and paraphrased questions (`tests/rag_eval`). The files and",
        "questions are in the repository; nothing here was measured on anyone's own files.",
        "",
        "**Right file first** is how often the file that answers the question is the top result;",
        "**right file in top 5** how often it is among the first five. One question in five is held",
        "out from all tuning, so the scores aren't fitted to the questions.",
        "",
    ]
    if base:
        out += [
            "## Built-in search (every install, checked on every commit)",
            "",
            "The lexical vectors that work without an AI model. CI fails when any of these drops by",
            "more than 0.01.",
            "",
        ]
        out += _table(_by_lang(base)) + [""]
        if _split(base):
            out += [_split(base), ""]
    if docs:
        out += ["Long, Office and scanned documents:", ""] + _table(_by_kind(docs), all5=True) + [""]
    if ext:
        out += (
            [
                "Questions that share few words with the file, which lexical vectors can't match by design",
                "(the neural model below can):",
                "",
            ]
            + _table(_by_kind(ext))
            + [""]
        )
    if night:
        out += [
            f"## With the {_model(night['model'])} model (nightly, on GitHub's runners)",
            "",
            f"The same sets with {_model(night['model'])} as the embedder and {night.get('distractors', 0):,} extra files"
            " that answer nothing, to make finding the right one harder. " + (_sentence(night.get("note", ""))),
            "",
        ]
        out += _table(_by_lang(night)) + [""] + _table(_by_kind(night)) + [""]
        if _split(night):
            out += [_split(night), ""]
    if night_docs:
        out += ["Long, Office and scanned documents:", ""] + _table(_by_kind(night_docs), all5=True) + [""]
    a = (night_ans or {}).get("answers")
    if a:
        out += [
            f"## Answers (nightly, {_model(a['model'])} as the chat model)",
            "",
            "| | |",
            "|---|---|",
            f"| Answer contains the right fact | {_n(a.get('accuracy'))} |",
            f"| The file it came from is cited | {_n(a.get('source_hit'))} |",
            f"| Says it can't find it, when the files don't have the answer | {_n(a.get('says_not_found'))} |",
            f"| Answer sentences the strict source check could match | {_n(a.get('faithfulness'))} |",
            "",
            "The source check is the one the chat shows under each answer (see [RAG.md](RAG.md#how-answers-are-checked)):",
            "every number in a sentence must appear in the source it leans on, and the rest must match it.",
            "It is deliberately strict, so a right answer in other words often counts as unmatched.",
            "",
        ]
    out += [
        "## Run it yourself",
        "",
        "```bash",
        "python -m tests.rag_eval.run_eval                                        # built-in search",
        "python -m tests.rag_eval.run_eval --model embeddinggemma --set all       # with a model on your NAS",
        "```",
        "",
        "The method, the sets and what each score means are in [RAG.md](RAG.md#measured-retrieval-quality).",
        "",
    ]
    return "\n".join(out)


def main(argv) -> int:
    page = render()
    if "--update" in argv:
        with open(PAGE, "w", encoding="utf-8") as fh:
            fh.write(page)
        print("wrote docs/SEARCH_QUALITY.md")
        return 0
    try:
        with open(PAGE, encoding="utf-8") as fh:
            current = fh.read()
    except FileNotFoundError:
        current = ""
    if current != page:
        print("docs/SEARCH_QUALITY.md is out of date: python scripts/search_quality_page.py --update")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
