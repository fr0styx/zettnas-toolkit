"""Built-in App Catalog templates ("ZettNAS Curated Suite").

Each template is deployed by backend/services/app_catalog.py through the Docker API:

  id, name, category, description, image   required
  default_port      host port suggested in the deploy dialog; it maps to the container port in
                    `ports` whose host or container side equals it (else to the same port)
  ports             extra "host:container[/proto]" mappings
  webui_path        path of the web UI; webui_scheme "https" when the app only serves HTTPS
  env, volumes      environment and named folders (created under appdata/<app>)
  stack_services    companion containers on a private network (database, cache, …)
  command           list: overrides the image's command
  cap_add, sysctls  extra capabilities / kernel settings the app needs
  devices           host devices passed through when the host has them (e.g. /dev/dri)
  seed_files        {volume: {relative path: content}} written once, before first start
  volume_owner      "uid:gid" the app runs as; its folders are handed to it on install
  credentials       login shown after deploy; "{{secret:name}}" makes and keeps a password
  probe             "tcp" when the app has no web UI (game servers); webui_path is None
  logo              icon name from the dashboard-icons set (cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons)

Every template here was deployed on a real host and its web UI answered before it was added
(scripts/verify_catalog.py repeats that check).
"""

